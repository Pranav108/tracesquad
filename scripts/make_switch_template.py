"""Build the Switch agent template (6 agents + one room) from prompts/*.md.

Usage: python3 scripts/make_switch_template.py [--auto-approve]
Writes switch/bug-agents.template.yaml. Import it in Switch Console (Templates -> Import template).
Re-run after the prompts change (scripts/tunnel.sh rewrites the URL in both).
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AGENTS = [
    ("triage", "Triage", "Front door: duplicates, the real user, first classification"),
    ("telios", "Telios", "Builds mock users and fetches app builds in the sandbox"),
    ("kinetics", "Kinetics", "Reproduces bugs in the app and verifies fixes"),
    ("espida", "Espida", "Reads logs, traces, deploys and impact"),
    ("atlas", "Atlas", "Finds the culprit change and ships the fix"),
    ("gremlin", "Gremlin", "Product and program manager: PRDs, releases, threads, final RCA"),
]
NAMES = ", ".join(name for name, _, _ in AGENTS)

SWITCH_NOTES = f"""
## Working in this Switch room

- Your teammates are agents in this room: {NAMES}. To send any protocol message ([ASK], [ANSWER],
  [NOT MINE], [CLAIM], [REPORT], [RCA]) to a specific teammate, use the `send_targeted_message` tool
  with `target_names` set to their name (e.g. ["telios"]) and the bug thread's `thread_id`, so the
  conversation stays in one thread. A plain message reaches only the people in the room.
- An agent wakes up only when it is addressed. Address exactly the agent you need; don't broadcast.
- Use `read_context` to catch up on the thread before asking anything.
- Call the Bugmock API with `curl -s` from your shell (add `-H 'Content-Type: application/json'` and
  `-d '<json>'` for POST). Parse JSON with `python3 -c` or `jq` if present. Never invent responses.
"""


def block(text: str, indent: int) -> str:
    pad = " " * indent
    return "\n".join((pad + line) if line.strip() else "" for line in text.rstrip().split("\n"))


def build(auto_approve: bool) -> str:
    out = [
        "# Generated by scripts/make_switch_template.py from prompts/*.md. Do not edit by hand.",
        "version: 1",
        "",
        "params:",
        "  provider:",
        "    type: provider",
        "    description: Which coding agent backs the agents. The first one installed is chosen.",
        "    default: [claude, codex]",
        "    input: advanced",
        "  location:",
        "    type: location",
        "    description: The machine the agents run on.",
        "    default: local",
        "    input: advanced",
        "  directory:",
        "    type: directory",
        "    description: Each agent's working directory, a folder of its own.",
        '    default: "{$agents_dir}/{agent}"',
        "    input: advanced",
        "  bridge:",
        "    type: bridge",
        "    description: Where the room is mirrored (Mattermost).",
        "    default: [$first]",
        "",
        "agents:",
    ]
    for name, display, description in AGENTS:
        prompt = (ROOT / "prompts" / f"{name}.md").read_text() + SWITCH_NOTES
        out += [
            f"  - name: {name}",
            f"    display_name: {display}",
            f"    description: {json.dumps(description)}",
            "    addressing: anyone",
            '    provider: "{provider}"',
            '    location: "{location}"',
            '    directory: "{directory}"',
        ]
        if auto_approve:
            out.append("    auto_approve: true")
        out += ["    instructions: |", block(prompt, 6)]
    out += [
        "",
        "room:",
        "  name: bug-channel",
        "  description: Bug reports, and the six agents that reproduce, fix and close them",
        '  bridge: "{bridge}"',
        f"  agents: [{NAMES}]",
        '  users: ["{$creator}"]',
        "  instructions: |",
        block(f"Bug reports are posted here. The agents are {NAMES}. Each owns one area (see their"
              " instructions). To hand work to a teammate, use send_targeted_message with target_names,"
              " in the bug's thread. Post status updates in the thread, not as new top-level posts.", 4),
        "",
        "kickoff: |",
        block("@triage @telios @kinetics @espida @atlas @gremlin: this is the bug channel. Each of you,"
              " say hello in one line: your name and what you own. Then wait for a bug report.", 2),
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    target = ROOT / "switch" / "bug-agents.template.yaml"
    target.parent.mkdir(exist_ok=True)
    target.write_text(build("--auto-approve" in sys.argv))
    print(f"wrote {target.relative_to(ROOT)} ({target.stat().st_size // 1024} KB)")
