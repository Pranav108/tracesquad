"""Build the Switch template for TraceSquad (six agents and their room) from squad.yaml and prompts/*.md.

Usage:
    uv run python scripts/make_switch_template.py           writes switch/tracesquad.template.yaml
    uv run python scripts/make_switch_template.py --check   exits 1 if that file is out of date

The template is `version: 2`, so a Switch agent (switch-buddy) can create everything in one call with
create_room_from_yaml, or save it with save_template and run it with run_template. People can import it
in Switch Console (Templates). Re-run after changing a prompt or squad.yaml. It never contains the API's
URL: agents find the API with `tsq` (see SWITCH.md), so a new URL needs no new template.
"""

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "switch" / "tracesquad.template.yaml"
SQUAD = yaml.safe_load((ROOT / "squad.yaml").read_text())
AGENTS = SQUAD["agents"]
NAMES = [a["name"] for a in AGENTS]
ROOM = SQUAD["deploy"]["room"]

# Switch reads any `{word}` in a template as a placeholder and warns about each one no param declares,
# and save_template refuses a document with warnings. Path params in the prompts (`/fixes/{fix_id}`)
# are written `/fixes/<fix_id>` in the template instead; agents read both the same way.
BRACED = re.compile(r"\{(\$?[A-Za-z_][A-Za-z0-9_]*)\}")

SWITCH_NOTES = f"""
## Working in this Switch room

- Your teammates are agents in this room: {", ".join(NAMES)}. To send any protocol message ([ASK],
  [ANSWER], [NOT MINE], [CLAIM], [REPORT], [NUDGE], [CLOSE], [RCA]) to a specific teammate, use the
  `send_targeted_message` tool with `target_names` set to the agents in your header's `to=` (e.g.
  ["telios"]) and the bug thread's `thread_id`, so the conversation stays in one thread. A plain
  message reaches only the people in the room: a `to=` without `target_names` wakes nobody.
- An agent wakes up only when it is addressed. Address exactly the agent you need; don't broadcast.
  Write teammates' names bare in message text; an at-sign before a name addresses that agent for real.
- Nothing in Switch runs on a timer. Triage's checks for stuck bugs are woken by a `sweep` message
  that the operator (or a scheduled post) sends it about every 10 minutes.
- Use `read_context` to catch up on the thread before asking anything.
- Call the TraceSquad API only with `~/.tracesquad/bin/tsq` from your shell (see "Tools" above).
  Parse its JSON with `python3 -c` or `jq` if present. Never invent a response, and never go looking
  for the API's address, its source or its data files on this machine: everything you know comes from
  `tsq` and from your teammates.
"""


def q(text: str) -> str:
    """A one-line YAML string (JSON is valid YAML)."""
    return json.dumps(text, ensure_ascii=False)


def block(text: str, indent: int) -> str:
    pad = " " * indent
    return "\n".join((pad + line) if line.strip() else "" for line in text.rstrip().split("\n"))


def instructions_for(agent: dict) -> str:
    prompt = (ROOT / agent["prompt"]).read_text() + SWITCH_NOTES
    return BRACED.sub(r"<\1>", prompt)


def build() -> str:
    out = [
        "# TraceSquad: six bug agents and the room they work in, for Switch.",
        "# Generated by scripts/make_switch_template.py from squad.yaml and prompts/*.md. Do not edit by hand.",
        "# How to deploy it, and how the agents find the API without a URL in here: SWITCH.md.",
        "version: 2",
        "",
        "params:",
        "  bridge:",
        "    type: bridge",
        "    label: Messaging app",
        "    description: Where the squad's room is made. Slack when it is set up, else the server's default app.",
        "    default: [Slack, $first]",
        "    required: false",
        "  provider:",
        "    type: provider",
        "    description: The coding agent that runs each of the six. The first one ready on the machine is chosen.",
        "    default: [claude, codex]",
        "    input: advanced",
        "  machine:",
        "    type: machine",
        "    description: The machine all six run on. Pick the one running the TraceSquad API (scripts/serve.sh).",
        "    default: [$first]",
        "    input: advanced",
        "  bypass:",
        "    type: boolean",
        "    label: Run without asking",
        "    description: >-",
        "      Let the agents run every command without asking you first. Off, each agent's provider still",
        "      runs safe commands by itself and asks before risky ones.",
        "    default: false",
        "    input: advanced",
        "",
        "form:",
        "  advanced: { label: Advanced, open: false }",
        "",
        "resources:",
    ]
    for agent in AGENTS:
        name = agent["name"]
        out += [
            f"  {name}:",
            "    type: agent",
            f"    name: {name}",
            f"    display_name: {q(agent['display_name'])}",
            f"    description: {q(agent['description'])}",
            '    provider: "{provider}"',
            '    machine: "{machine}"',
            f'    directory: "{{$agents_dir}}/{{{name}.name}}"',
            "    addressing: anyone",
            '    auto_approve: "{bypass}"',
            "    instructions: |",
            block(instructions_for(agent), 6),
            "",
        ]
    names = ", ".join(NAMES)
    mentions = " ".join(f"@{{{n}.name}}" for n in NAMES)
    out += [
        "  squad_room:",
        "    type: room",
        f"    name: {ROOM}",
        f"    description: {q('Bug reports, and the six TraceSquad agents that reproduce, fix and close them')}",
        '    bridge: "{bridge}"',
        f"    agents: [{names}]",
        "    users:",
        '      - if: "{bridge}"',
        '        value: ["{$creator}"]',
        "      - value: []",
        "    instructions: |",
        block(f"Bug reports are posted here. The agents are {names}. Each owns one area (see their"
              " instructions). To hand work to a teammate, use send_targeted_message with target_names,"
              " in the bug's thread. Post status updates in the thread, not as new top-level posts."
              " Triage keeps bugs moving and closes every bug that isn't fixed; Gremlin's RCA closes a"
              " fixed bug. About every 10 minutes, someone outside the agents sends triage the word"
              " sweep, so it checks for stuck bugs.", 6),
        "    kickoff: |",
        block(f"{mentions}: this is the TraceSquad bug room. Each of you, check that"
              " `~/.tracesquad/bin/tsq GET /health` answers, then say hello in one line: your name, what"
              " you own, and whether the API answered. Then wait for a bug report.", 6),
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date; run: uv run python scripts/make_switch_template.py")
            sys.exit(1)
        print(f"{TARGET.relative_to(ROOT)} is up to date")
        sys.exit(0)
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)} ({TARGET.stat().st_size // 1024} KB)")
