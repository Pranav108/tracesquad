"""Build the Switch template for TraceSquad (six agents, the public room and the work log) from squad.yaml and prompts/*.md.

Usage:
    uv run python scripts/make_switch_template.py           writes switch/tracesquad.template.yaml
    uv run python scripts/make_switch_template.py --check   exits 1 if that file is out of date

The template is `version: 2`, so a Switch agent (switch-buddy) can create everything in one call with
create_room_from_yaml, or save it with save_template and run it with run_template. People can import it
in Switch Console (Templates). Re-run after changing a prompt or squad.yaml. It never contains the API's
URL: agents find the API with `tsq` (see SWITCH.md), so a new URL needs no new template.
"""

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "switch" / "tracesquad.template.yaml"
SQUAD = yaml.safe_load((ROOT / "squad.yaml").read_text())
AGENTS = SQUAD["agents"]
NAMES = [a["name"] for a in AGENTS]
ROOMS = SQUAD["deploy"]["rooms"]
PUBLIC_ROOM, WORK_LOG_ROOM = ROOMS["public"], ROOMS["work_log"]

# Switch reads any `{word}` in a template as a placeholder and warns about each one no param declares,
# and save_template refuses a document with warnings. Path params in the prompts (`/fixes/{fix_id}`)
# are written `/fixes/<fix_id>` in the template instead; agents read both the same way.
BRACED = re.compile(r"\{(\$?[A-Za-z_][A-Za-z0-9_]*)\}")

SWITCH_NOTES = f"""
## Working in Switch

- You are in two rooms. The **work log room** (only the team can read it) is where you work: every
  protocol message goes there, in the bug's thread. The **public room** is where people report
  bugs. Never post in the public room. If you are woken there, end your turn without posting: the
  herald brings every report and every reply to the work log, where Triage picks it up.
- Your teammates are agents in the work log room: {", ".join(NAMES)}. To send any protocol message
  ([ASK], [ANSWER], [NOT MINE], [CLAIM], [REPORT], [NUDGE], [CLOSE], [RCA]) to a specific teammate,
  use the `send_targeted_message` tool with `target_names` set to the agents in your header's `to=`
  (e.g. ["telios"]) and the bug thread's `thread_id`, so the conversation stays in one thread. A
  plain message reaches only the people in the room: a `to=` without `target_names` wakes nobody.
  Triage's [PUBLIC] is the one plain message: `post_message` with the bug thread's `thread_id`.
- An agent wakes up only when it is addressed. Address exactly the agent you need; don't broadcast.
  Write teammates' names bare in message text; an at-sign before a name addresses that agent for real.
- Nothing in Switch runs on a timer. Triage's checks for stuck bugs are woken by a `sweep` message
  that the operator (or a scheduled post) sends it about every 10 minutes.
- Use `read_context` to catch up on the thread before asking anything.
- Call the TraceSquad API only with `~/.tracesquad/bin/tsq` from your shell (see "Tools" above).
  Parse its JSON with `python3 -c` or `jq` if present. Never invent a response, and never go looking
  for the API's address, its source or its data files on this machine: everything you know comes from
  `tsq` and from your teammates.
"""


def q(text: str) -> str:
    """A one-line YAML string (JSON is valid YAML)."""
    return json.dumps(text, ensure_ascii=False)


def block(text: str, indent: int) -> str:
    pad = " " * indent
    return "\n".join((pad + line) if line.strip() else "" for line in text.rstrip().split("\n"))


def instructions_for(agent: dict) -> str:
    prompt = (ROOT / agent["prompt"]).read_text() + SWITCH_NOTES
    return BRACED.sub(r"<\1>", prompt)


def build() -> str:
    out = [
        "# TraceSquad: six bug agents, the public room bugs are reported in, and the private work log they work in, for Switch.",
        "# Generated by scripts/make_switch_template.py from squad.yaml and prompts/*.md. Do not edit by hand.",
        "# How to deploy it (and the herald that links the two rooms), and how the agents find the API without a URL in here: SWITCH.md.",
        "version: 2",
        "",
        "params:",
        "  bridge:",
        "    type: bridge",
        "    label: Messaging app",
        "    description: Where the squad's room is made. Slack when it is set up, else the server's default app.",
        "    default: [Slack, $first]",
        "    required: false",
        "  provider:",
        "    type: provider",
        "    description: The coding agent that runs each of the six. The first one ready on the machine is chosen.",
        "    default: [claude, codex]",
        "    input: advanced",
        "  machine:",
        "    type: machine",
        "    description: The machine all six run on. Pick the one running the TraceSquad API (scripts/serve.sh).",
        "    default: [$first]",
        "    input: advanced",
        "  bypass:",
        "    type: boolean",
        "    label: Run without asking",
        "    description: >-",
        "      Let the agents run every command without asking you first. Off, each agent's provider still",
        "      runs safe commands by itself and asks before risky ones.",
        "    default: false",
        "    input: advanced",
        "",
        "form:",
        "  advanced: { label: Advanced, open: false }",
        "",
        "resources:",
    ]
    for agent in AGENTS:
        name = agent["name"]
        out += [
            f"  {name}:",
            "    type: agent",
            f"    name: {name}",
            f"    display_name: {q(agent['display_name'])}",
            f"    description: {q(agent['description'])}",
            '    provider: "{provider}"',
            '    machine: "{machine}"',
            f'    directory: "{{$agents_dir}}/{{{name}.name}}"',
            "    addressing: anyone",
            '    auto_approve: "{bypass}"',
            "    instructions: |",
            block(instructions_for(agent), 6),
            "",
        ]
    names = ", ".join(NAMES)
    mentions = " ".join(f"@{{{n}.name}}" for n in NAMES)
    users = ["    users:", '      - if: "{bridge}"', '        value: ["{$creator}"]', "      - value: []"]
    out += [
        "  squad_group:",
        "    type: group",
        "    name: TraceSquad",
        f"    description: {q('Where people report app bugs, and the private work log where the six agents work them')}",
        "    links:",
        f"      - {{from: public_room, to: work_log_room, label: {q('the work log for these bugs (team only)')}}}",
        "",
        "  public_room:",
        "    type: room",
        f"    name: {PUBLIC_ROOM}",
        f"    description: {q('Report app bugs here, one new post per bug (no tag needed). Each bug gets a status card; the squad works it in the work log')}",
        '    bridge: "{bridge}"',
        "    channel_type: channel_public",
        "    group: squad_group",
        # Triage is a member so that a report that still tags @triage resolves. It never posts here: the
        # herald opens a bug for every new post, tagged or not.
        f"    agents: [{SQUAD['topology']['owner_of_every_bug']}]",
        *users,
        "    instructions: |",
        block("This is the public room: anyone in the community reads it. Every new post here is a bug"
              " report, and replies are the discussion; nobody needs to tag anyone. Agents never post in"
              " this room. If you are woken here, end your turn"
              " without posting: the herald (a program, not an agent) opens each bug's thread in the work"
              " log room and hands the report to Triage there, posts a status card in the reporter's"
              " thread and keeps it current, and copies Triage's [PUBLIC] messages back here.", 6),
        "",
        "  work_log_room:",
        "    type: room",
        f"    name: {WORK_LOG_ROOM}",
        f"    description: {q('The TraceSquad work log: the six agents work each bug here, one thread per bug (team only)')}",
        '    bridge: "{bridge}"',
        "    channel_type: channel_private",
        "    group: squad_group",
        f"    agents: [{names}]",
        *users,
        "    instructions: |",
        block(f"This is the work log: only the team reads it. The agents are {names}. Each owns one area"
              " (see their instructions). The herald opens one thread per bug with a [NEW BUG] to triage;"
              " the whole squad works that bug in that thread. To hand work to a teammate, use"
              " send_targeted_message with target_names, in the bug's thread. Don't post status updates:"
              " the herald's card in the public room shows the progress, built from your headers. Triage"
              " keeps bugs moving and closes every bug that isn't fixed; Gremlin's RCA closes a fixed bug."
              " Only Triage talks to the reporter, with [PUBLIC]. About every 10 minutes, someone outside"
              " the agents sends triage the word sweep, so it checks for stuck bugs.", 6),
        "    kickoff: |",
        block(f"{mentions}: this is the TraceSquad work log. Each of you, check that"
              " `~/.tracesquad/bin/tsq GET /health` answers, then say hello in one line: your name, what"
              " you own, and whether the API answered. Then wait for a bug: the herald opens a thread"
              " here for each one.", 6),
        "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date; run: uv run python scripts/make_switch_template.py")
            sys.exit(1)
        print(f"{TARGET.relative_to(ROOT)} is up to date")
        sys.exit(0)
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)} ({TARGET.stat().st_size // 1024} KB)")
